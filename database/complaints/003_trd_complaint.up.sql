-- =====================================================================
-- Модуль «Жалобы»: решение по жалобам на закупку.
--
--   trd_complaint         решение: один цикл обжалования закупки
--   trd_complaint_member  участники: рассматривающий, согласующий, утверждающий
--   trd_complaint_lots    решение по лоту закупки и его исполнение
--   trd_complaint_date    сроки: обжалования, рассмотрения, исполнения
--   trd_complaint_docs    сводный документ, ответы по лоту и файлы к ним
--
-- Файлы 001–004 выполняются вместе в одной транзакции:
--   psql --single-transaction -f 001_… -f 002_… -f 003_… -f 004_…
--
-- Соглашения:
--   - id — GENERATED BY DEFAULT: php-activerecord может вставлять id явно;
--   - пользователи, организации (*_user_id, *_subject_id, member_id,
--     cruser_id, crsubject_id) и файлы (fls_stg_entity_id) — без REFERENCES;
--   - срок — полуинтервал [start_at, end_at): end_at — 00:00 дня,
--     следующего за последним днём срока;
--   - статус исполнения решения входит в status_id (5, 6, 7), статус
--     исполнения лота следует из execution_started_at и executed_at;
--   - номер решения — id.
--
-- ПРОЕКТ: имена таблиц проекта trd_buy_lot (здесь и в 004), trd_app
-- и trd_app_lot (в 004) выведены из имён столбцов схемы; если таблицы
-- называются иначе, поправьте REFERENCES.
--
-- Не обеспечивается СУБД, проверяет PHP:
--   - лот закупки trd_complaint_lots.trd_buy_lot_id принадлежит закупке решения;
--   - одно решение на закупку и срок обжалования (advisory-блокировка закупки);
--   - участники маршрута назначены до отправки на согласование.
-- =====================================================================

CREATE TABLE trd_complaint (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trd_buy_id             bigint      NOT NULL REFERENCES trd_buy (id),
    status_id              bigint      NOT NULL DEFAULT 1 REFERENCES ref_trd_complaint_st (id),
    method_id              bigint      REFERENCES ref_complaint_review_method (id),
    step                   smallint,
    lots_count             integer     NOT NULL DEFAULT 0,
    app_complaint_count    integer     NOT NULL DEFAULT 0,

    sent_for_approval_at   timestamptz,   -- рассматривающий отправил (с согласующим и без)
    sent_by_user_id        bigint,
    sent_by_subject_id     bigint,
    coordinated_at         timestamptz,   -- согласующий подписал и передал утверждающему
    approved_at            timestamptz,
    recalled_at            timestamptz,   -- последний отзыв с маршрута
    recalled_by_user_id    bigint,
    recalled_by_subject_id bigint,

    cruser_id              bigint,        -- решение создаёт система при сборе жалоб: пусто
    crsubject_id           bigint      NOT NULL,   -- уполномоченный орган
    deleted_at             timestamptz,

    -- Цель составного ключа жалобы: жалоба собирается в решение своей закупки.
    CONSTRAINT uq_trd_complaint_id_buy
        UNIQUE (id, trd_buy_id),
    CONSTRAINT chk_trd_complaint_counts
        CHECK (lots_count >= 0 AND app_complaint_count >= 0),
    CONSTRAINT chk_trd_complaint_sent_by
        CHECK ((sent_for_approval_at IS NULL) = (sent_by_user_id IS NULL)
           AND (sent_by_user_id IS NULL) = (sent_by_subject_id IS NULL)),
    CONSTRAINT chk_trd_complaint_recalled_by
        CHECK ((recalled_at IS NULL) = (recalled_by_user_id IS NULL)
           AND (recalled_by_user_id IS NULL) = (recalled_by_subject_id IS NULL)),
    CONSTRAINT chk_trd_complaint_coordinated_after_sending
        CHECK (coordinated_at IS NULL OR sent_for_approval_at IS NOT NULL),
    -- На маршруте и после утверждения: способ ответа выбран, решение отправлено.
    CONSTRAINT chk_trd_complaint_sent
        CHECK (status_id NOT IN (2, 3, 5, 6, 7)
            OR (method_id IS NOT NULL AND sent_for_approval_at IS NOT NULL)),
    CONSTRAINT chk_trd_complaint_recalled
        CHECK (status_id <> 4 OR recalled_at IS NOT NULL),
    CONSTRAINT chk_trd_complaint_approved
        CHECK ((status_id IN (5, 6, 7)) = (approved_at IS NOT NULL))
);

COMMENT ON TABLE trd_complaint IS 'Жалобы: решение по жалобам на закупку, один цикл обжалования';
COMMENT ON COLUMN trd_complaint.method_id IS 'Способ ответа: по каждой жалобе или одним ответом по лоту';
COMMENT ON COLUMN trd_complaint.step IS 'Не заполняется модулем';
COMMENT ON COLUMN trd_complaint.crsubject_id IS 'Уполномоченный орган, рассматривающий жалобы';

CREATE INDEX ix_trd_complaint_buy
    ON trd_complaint (trd_buy_id);

CREATE INDEX ix_trd_complaint_subject_status
    ON trd_complaint (crsubject_id, status_id)
    WHERE deleted_at IS NULL;


-- Одна строка на роль: рассматривающий закрепляется за решением сам,
-- согласующего (необязателен) и утверждающего назначает рассматривающий
-- при отправке. Снятие закрепления и отзыв удаляют строки.
CREATE TABLE trd_complaint_member (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trd_complaint_id          bigint      NOT NULL REFERENCES trd_complaint (id),
    ref_trd_complaint_role_id bigint      NOT NULL REFERENCES ref_trd_complaint_role (id),
    member_id                 bigint      NOT NULL,   -- пользователь
    member_subject_id         bigint      NOT NULL,   -- его организация
    assigned_by_user_id       bigint      NOT NULL,
    assigned_by_subject_id    bigint      NOT NULL,
    created_at                timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_trd_complaint_member_role
        UNIQUE (trd_complaint_id, ref_trd_complaint_role_id)
);

COMMENT ON TABLE trd_complaint_member IS 'Жалобы: участники рассмотрения решения';

CREATE INDEX ix_trd_complaint_member_member
    ON trd_complaint_member (member_id);


CREATE TABLE trd_complaint_lots (
    id                              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trd_complaint_id                bigint      NOT NULL REFERENCES trd_complaint (id),
    decision_id                     bigint      REFERENCES ref_trd_complaint_lots_decision (id),
    trd_buy_lot_id                  bigint      NOT NULL REFERENCES trd_buy_lot (id),
    app_complaint_count             integer     NOT NULL DEFAULT 0,
    execution_started_at            timestamptz,   -- организатор отменил лот или запустил пересмотр
    execution_started_by_user_id    bigint,
    execution_started_by_subject_id bigint,
    executed_at                     timestamptz,   -- лот отменён или протокол опубликован повторно
    created_at                      timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_trd_complaint_lots_buy_lot
        UNIQUE (trd_complaint_id, trd_buy_lot_id),
    -- Цели составных ключей: лот жалобы и документ лота — того же решения и лота закупки.
    CONSTRAINT uq_trd_complaint_lots_id_buy_lot
        UNIQUE (id, trd_buy_lot_id),
    CONSTRAINT uq_trd_complaint_lots_id_complaint
        UNIQUE (id, trd_complaint_id),
    CONSTRAINT chk_trd_complaint_lots_count
        CHECK (app_complaint_count >= 0),
    CONSTRAINT chk_trd_complaint_lots_started_by
        CHECK ((execution_started_by_user_id IS NULL) = (execution_started_by_subject_id IS NULL)
           AND (execution_started_by_user_id IS NULL OR execution_started_at IS NOT NULL)),
    CONSTRAINT chk_trd_complaint_lots_executed_after_start
        CHECK (executed_at IS NULL OR execution_started_at IS NOT NULL),
    -- Исполняются только отмена закупки (1) и пересмотр итогов (2).
    CONSTRAINT chk_trd_complaint_lots_execution_needs_decision
        CHECK (execution_started_at IS NULL OR decision_id IN (1, 2))
);

COMMENT ON TABLE trd_complaint_lots IS 'Жалобы: решение по лоту закупки и его исполнение';

CREATE INDEX ix_trd_complaint_lots_buy_lot
    ON trd_complaint_lots (trd_buy_lot_id);

CREATE INDEX ix_trd_complaint_lots_under_revision
    ON trd_complaint_lots (trd_complaint_id)
    WHERE execution_started_at IS NOT NULL AND executed_at IS NULL;


-- Срок каждого вида — один на решение. name_ru и name_kz копируются
-- из справочника видов сроков при создании строки.
CREATE TABLE trd_complaint_date (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_type_id     bigint       NOT NULL REFERENCES ref_trd_complaint_date_type (id),
    trd_complaint_id bigint       NOT NULL REFERENCES trd_complaint (id),
    name_ru          varchar(200) NOT NULL,
    name_kz          varchar(200) NOT NULL,
    start_at         timestamptz  NOT NULL,
    end_at           timestamptz  NOT NULL,   -- 00:00 дня после последнего дня срока
    created_at       timestamptz  NOT NULL DEFAULT now(),

    CONSTRAINT uq_trd_complaint_date_type
        UNIQUE (trd_complaint_id, date_type_id),
    CONSTRAINT chk_trd_complaint_date_period
        CHECK (start_at < end_at)
);

COMMENT ON TABLE trd_complaint_date IS 'Жалобы: сроки решения [start_at, end_at)';

CREATE INDEX ix_trd_complaint_date_type_end
    ON trd_complaint_date (date_type_id, end_at);


-- Документы решения. id документа в модуле — fls_stg_entity_id (файл
-- в хранилище проекта); подписи хранятся у файла в проекте.
--   1 сводный документ ответов   trd_complaint_lots_id пуст
--   2 ответ по лоту (способ «одним ответом по лоту»)
--   3 файл к ответу по лоту
-- Действующая версия — deleted_at IS NULL; номер версии — порядковый.
CREATE TABLE trd_complaint_docs (
    id                             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trd_complaint_id               bigint      NOT NULL REFERENCES trd_complaint (id),
    trd_complaint_lots_id          bigint,
    ref_trd_complaint_docs_type_id bigint      NOT NULL REFERENCES ref_trd_complaint_docs_type (id),
    fls_stg_entity_id              bigint      NOT NULL,
    cruser_id                      bigint      NOT NULL,
    crsubject_id                   bigint      NOT NULL,
    created_at                     timestamptz NOT NULL DEFAULT now(),
    deleted_at                     timestamptz,

    CONSTRAINT fk_trd_complaint_docs_lot
        FOREIGN KEY (trd_complaint_lots_id, trd_complaint_id)
        REFERENCES trd_complaint_lots (id, trd_complaint_id),
    CONSTRAINT uq_trd_complaint_docs_file
        UNIQUE (fls_stg_entity_id),
    CONSTRAINT chk_trd_complaint_docs_lot
        CHECK ((ref_trd_complaint_docs_type_id = 1) = (trd_complaint_lots_id IS NULL))
);

COMMENT ON TABLE trd_complaint_docs IS 'Жалобы: документы решения (файлы проекта)';

CREATE UNIQUE INDEX uq_trd_complaint_docs_current_consolidated
    ON trd_complaint_docs (trd_complaint_id)
    WHERE ref_trd_complaint_docs_type_id = 1 AND deleted_at IS NULL;

CREATE UNIQUE INDEX uq_trd_complaint_docs_current_answer
    ON trd_complaint_docs (trd_complaint_lots_id)
    WHERE ref_trd_complaint_docs_type_id = 2 AND deleted_at IS NULL;

CREATE INDEX ix_trd_complaint_docs_lot_type
    ON trd_complaint_docs (trd_complaint_lots_id, ref_trd_complaint_docs_type_id)
    WHERE trd_complaint_lots_id IS NOT NULL;
