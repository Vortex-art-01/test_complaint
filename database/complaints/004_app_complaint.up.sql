-- =====================================================================
-- Модуль «Жалобы»: жалоба поставщика на уровне заявки.
--
--   app_complaint         жалоба поставщика по своей заявке
--   app_complaint_answer  ответ уполномоченного органа
--   app_complaint_lots    лот жалобы: вердикт и ссылка на ответ
--   app_complaint_docs    PDF жалобы, приложения, ответы по каждой жалобе
--
-- Выполняется вместе с 001–003 в одной транзакции.
--
-- Номер жалобы на экранах и в PDF — «Ж-» и id из шести цифр.
--
-- Ответ: при способе «по каждой жалобе» у лота жалобы свой ответ,
-- при способе «одним ответом по лоту» один ответ на все жалобы лота
-- закупки. Составной ключ (answer_id, trd_complaint_lots_id) не даёт
-- сослаться на ответ другого лота решения.
--
-- Не обеспечивается СУБД, проверяет PHP:
--   - лот заявки принадлежит заявке жалобы, заявка — организации crsubject_id;
--   - не больше одной неудалённой и ещё не собранной жалобы на лот заявки
--     (advisory-блокировка лота заявки);
--   - статус заявки и лота заявки, дающий право на жалобу.
-- =====================================================================

CREATE TABLE app_complaint (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trd_complaint_id   bigint,                  -- заполняет система при сборе
    trd_buy_id         bigint       NOT NULL REFERENCES trd_buy (id),
    trd_app_id         bigint       NOT NULL REFERENCES trd_app (id),
    director_id        bigint       NOT NULL,   -- руководитель, подписывающий жалобу
    status_id          bigint       NOT NULL DEFAULT 1 REFERENCES ref_app_complaint_st (id),
    phone_number       varchar(50),             -- обязательны вне черновика
    description        varchar(2000),           -- лимит 500 знаков проверяет PHP
    step               smallint,
    date_apply         timestamptz,             -- последняя подача
    applyed_by_user_id bigint,
    cruser_id          bigint       NOT NULL,   -- автор
    crsubject_id       bigint       NOT NULL,   -- организация поставщика
    created_at         timestamptz  NOT NULL DEFAULT now(),
    deleted_at         timestamptz,

    -- Жалоба собирается в решение своей закупки.
    CONSTRAINT fk_app_complaint_trd_complaint
        FOREIGN KEY (trd_complaint_id, trd_buy_id) REFERENCES trd_complaint (id, trd_buy_id),
    CONSTRAINT chk_app_complaint_filled
        CHECK (status_id = 1 OR (phone_number IS NOT NULL AND description IS NOT NULL)),
    CONSTRAINT chk_app_complaint_applied_by
        CHECK ((date_apply IS NULL) = (applyed_by_user_id IS NULL)),
    -- Подана, отозвана, на рассмотрении, рассмотрена — подавалась.
    CONSTRAINT chk_app_complaint_applied
        CHECK (status_id NOT IN (4, 5, 6, 7) OR date_apply IS NOT NULL),
    -- В решении — только на рассмотрении и рассмотренные.
    CONSTRAINT chk_app_complaint_collected
        CHECK ((status_id IN (6, 7)) = (trd_complaint_id IS NOT NULL)),
    CONSTRAINT chk_app_complaint_deleted_before_submission
        CHECK (deleted_at IS NULL OR status_id IN (1, 2, 3))
);

COMMENT ON TABLE app_complaint IS 'Жалобы: жалоба поставщика по своей заявке';
COMMENT ON COLUMN app_complaint.step IS 'Не заполняется модулем';

CREATE INDEX ix_app_complaint_subject_created
    ON app_complaint (crsubject_id, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX ix_app_complaint_buy_submitted
    ON app_complaint (trd_buy_id)
    WHERE status_id = 4 AND trd_complaint_id IS NULL AND deleted_at IS NULL;

CREATE INDEX ix_app_complaint_trd_complaint
    ON app_complaint (trd_complaint_id)
    WHERE trd_complaint_id IS NOT NULL;

CREATE INDEX ix_app_complaint_app
    ON app_complaint (trd_app_id);


-- Смена способа ответа удаляет ответы решения: сначала снимаются ссылки
-- app_complaint_lots.answer_id.
CREATE TABLE app_complaint_answer (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trd_complaint_lots_id bigint         NOT NULL REFERENCES trd_complaint_lots (id),
    answer                varchar(20000) NOT NULL DEFAULT '',
    created_at            timestamptz    NOT NULL DEFAULT now(),

    -- Цель составного ключа лота жалобы.
    CONSTRAINT uq_app_complaint_answer_id_lot
        UNIQUE (id, trd_complaint_lots_id)
);

COMMENT ON TABLE app_complaint_answer IS 'Жалобы: ответ уполномоченного органа по лоту решения';

CREATE INDEX ix_app_complaint_answer_lot
    ON app_complaint_answer (trd_complaint_lots_id);


-- У жалобы один лот; в черновике лот меняют внутри той же заявки.
CREATE TABLE app_complaint_lots (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_complaint_id      bigint      NOT NULL REFERENCES app_complaint (id),
    trd_complaint_lots_id bigint,                -- заполняет система при сборе
    trd_buy_lot_id        bigint      NOT NULL REFERENCES trd_buy_lot (id),
    trd_app_lot_id        bigint      NOT NULL REFERENCES trd_app_lot (id),
    verdict_id            bigint      REFERENCES ref_app_complaint_lots_verdict (id),
    answer_id             bigint,
    cruser_id             bigint      NOT NULL,
    crsubject_id          bigint      NOT NULL,
    created_at            timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_app_complaint_lots_complaint
        UNIQUE (app_complaint_id),
    -- Цель составного ключа документов: документ лота — той же жалобы.
    CONSTRAINT uq_app_complaint_lots_id_complaint
        UNIQUE (id, app_complaint_id),
    -- Лот решения — по тому же лоту закупки.
    CONSTRAINT fk_app_complaint_lots_trd_lot
        FOREIGN KEY (trd_complaint_lots_id, trd_buy_lot_id)
        REFERENCES trd_complaint_lots (id, trd_buy_lot_id),
    -- Ответ — того же лота решения.
    CONSTRAINT fk_app_complaint_lots_answer
        FOREIGN KEY (answer_id, trd_complaint_lots_id)
        REFERENCES app_complaint_answer (id, trd_complaint_lots_id),
    -- Вердикт и ответ — только у собранной жалобы; без этого составной
    -- ключ ответа с пустым trd_complaint_lots_id не проверялся бы.
    CONSTRAINT chk_app_complaint_lots_reviewed_after_collection
        CHECK (trd_complaint_lots_id IS NOT NULL OR (verdict_id IS NULL AND answer_id IS NULL))
);

COMMENT ON TABLE app_complaint_lots IS 'Жалобы: лот жалобы, вердикт и ответ';

CREATE INDEX ix_app_complaint_lots_trd_lot
    ON app_complaint_lots (trd_complaint_lots_id)
    WHERE trd_complaint_lots_id IS NOT NULL;

CREATE INDEX ix_app_complaint_lots_app_lot
    ON app_complaint_lots (trd_app_lot_id);

CREATE INDEX ix_app_complaint_lots_answer
    ON app_complaint_lots (answer_id)
    WHERE answer_id IS NOT NULL;


-- Документы жалобы. id документа и вложения в модуле — fls_stg_entity_id
-- (файл в хранилище проекта); подпись руководителя хранится у файла в проекте.
--   1 жалоба (PDF)                  app_complaint_lots_id пуст
--   2 приложение к жалобе           app_complaint_lots_id пуст
--   3 ответ на жалобу (PDF)         способ «по каждой жалобе», лот с этим ответом
--   4 файл к ответу на жалобу       то же
-- Действующая версия — deleted_at IS NULL; номер версии — порядковый.
CREATE TABLE app_complaint_docs (
    id                             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_complaint_id               bigint      NOT NULL REFERENCES app_complaint (id),
    app_complaint_lots_id          bigint,
    ref_app_complaint_docs_type_id bigint      NOT NULL REFERENCES ref_app_complaint_docs_type (id),
    fls_stg_entity_id              bigint      NOT NULL,
    cruser_id                      bigint      NOT NULL,
    crsubject_id                   bigint      NOT NULL,
    created_at                     timestamptz NOT NULL DEFAULT now(),
    deleted_at                     timestamptz,

    CONSTRAINT fk_app_complaint_docs_lot
        FOREIGN KEY (app_complaint_lots_id, app_complaint_id)
        REFERENCES app_complaint_lots (id, app_complaint_id),
    CONSTRAINT uq_app_complaint_docs_file
        UNIQUE (fls_stg_entity_id),
    CONSTRAINT chk_app_complaint_docs_lot
        CHECK ((ref_app_complaint_docs_type_id IN (3, 4)) = (app_complaint_lots_id IS NOT NULL))
);

COMMENT ON TABLE app_complaint_docs IS 'Жалобы: документы жалобы (файлы проекта)';

CREATE UNIQUE INDEX uq_app_complaint_docs_current_complaint
    ON app_complaint_docs (app_complaint_id)
    WHERE ref_app_complaint_docs_type_id = 1 AND deleted_at IS NULL;

CREATE UNIQUE INDEX uq_app_complaint_docs_current_answer
    ON app_complaint_docs (app_complaint_lots_id)
    WHERE ref_app_complaint_docs_type_id = 3 AND deleted_at IS NULL;

CREATE INDEX ix_app_complaint_docs_complaint_type
    ON app_complaint_docs (app_complaint_id, ref_app_complaint_docs_type_id);

CREATE INDEX ix_app_complaint_docs_lot_type
    ON app_complaint_docs (app_complaint_lots_id, ref_app_complaint_docs_type_id)
    WHERE app_complaint_lots_id IS NOT NULL;
