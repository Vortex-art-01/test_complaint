-- =====================================================================
-- Модуль «Жалобы»: срок обжалования в закупке. Даты устанавливает проект
-- при публикации протокола итогов; модуль читает их как календарные дни
-- включительно (Asia/Almaty): с 00:00 первого дня до 23:59 последнего.
--
-- Новые столбцы без DEFAULT: таблица не переписывается, нужна только
-- короткая эксклюзивная блокировка; lock_timeout не даёт ей встать
-- в очередь за долгими транзакциями.
-- =====================================================================

SET lock_timeout = '5s';

ALTER TABLE trd_buy
    ADD COLUMN IF NOT EXISTS appeal_start_date date,
    ADD COLUMN IF NOT EXISTS appeal_end_date date;

COMMENT ON COLUMN trd_buy.appeal_start_date IS 'Жалобы: первый день срока обжалования';
COMMENT ON COLUMN trd_buy.appeal_end_date IS 'Жалобы: последний день срока обжалования включительно';
