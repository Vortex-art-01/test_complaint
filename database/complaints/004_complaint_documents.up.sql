-- =====================================================================
-- Модуль «Жалобы». Миграция 004: документы, подписи, вложения, история.
--
--   test_complaint_documents       сформированные PDF с версиями:
--                                  app_complaint / answer / consolidated_answer
--   test_complaint_signatures      ЭЦП версии документа и маршрут подписания
--   test_complaint_attachments     файлы к жалобе и к ответу
--   test_complaint_status_history  журнал переходов статусов, только INSERT
--
-- Выполняется вместе с 002 и 003 в одной транзакции.
-- Изменение содержимого подписанного документа — новая версия:
-- прежняя is_current = false, её подписи annulled.
-- =====================================================================

CREATE TABLE test_complaint_documents (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_type                  varchar(30) NOT NULL,
    test_app_complaint_id     bigint REFERENCES test_app_complaint (id),
    test_complaint_answers_id bigint REFERENCES test_complaint_answers (id),
    test_buy_complaint_id     bigint REFERENCES test_buy_complaint (id),

    version                   integer     NOT NULL DEFAULT 1,
    is_current                boolean     NOT NULL DEFAULT true,
    file_id                   bigint      NOT NULL,
    sha256                    varchar(64) NOT NULL,       -- хеш байтов PDF

    generated_by_user_id      bigint      NOT NULL,
    generated_at              timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chk_complaint_documents_owner
        CHECK ((doc_type = 'app_complaint'
                AND test_app_complaint_id IS NOT NULL
                AND test_complaint_answers_id IS NULL AND test_buy_complaint_id IS NULL)
            OR (doc_type = 'answer'
                AND test_complaint_answers_id IS NOT NULL
                AND test_app_complaint_id IS NULL AND test_buy_complaint_id IS NULL)
            OR (doc_type = 'consolidated_answer'
                AND test_buy_complaint_id IS NOT NULL
                AND test_app_complaint_id IS NULL AND test_complaint_answers_id IS NULL)),
    CONSTRAINT chk_complaint_documents_sha256
        CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    CONSTRAINT chk_complaint_documents_version
        CHECK (version > 0)
);

COMMENT ON TABLE test_complaint_documents IS
    'Жалобы: сформированные PDF (жалоба, ответ, сводный документ) с версиями';

CREATE UNIQUE INDEX uq_complaint_documents_current_app_complaint
    ON test_complaint_documents (test_app_complaint_id)
    WHERE is_current AND test_app_complaint_id IS NOT NULL;
CREATE UNIQUE INDEX uq_complaint_documents_current_answer
    ON test_complaint_documents (test_complaint_answers_id)
    WHERE is_current AND test_complaint_answers_id IS NOT NULL;
CREATE UNIQUE INDEX uq_complaint_documents_current_buy_complaint
    ON test_complaint_documents (test_buy_complaint_id)
    WHERE is_current AND test_buy_complaint_id IS NOT NULL;

CREATE UNIQUE INDEX uq_complaint_documents_version_app_complaint
    ON test_complaint_documents (test_app_complaint_id, version)
    WHERE test_app_complaint_id IS NOT NULL;
CREATE UNIQUE INDEX uq_complaint_documents_version_answer
    ON test_complaint_documents (test_complaint_answers_id, version)
    WHERE test_complaint_answers_id IS NOT NULL;
CREATE UNIQUE INDEX uq_complaint_documents_version_buy_complaint
    ON test_complaint_documents (test_buy_complaint_id, version)
    WHERE test_buy_complaint_id IS NOT NULL;


-- Жалоба: head. Сводный документ: reviewer -> coordinator -> approver.
CREATE TABLE test_complaint_signatures (
    id                          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_complaint_documents_id bigint      NOT NULL REFERENCES test_complaint_documents (id),
    signer_role                 varchar(30) NOT NULL,
    signer_user_id              bigint      NOT NULL,
    sign_order                  smallint    NOT NULL,

    status                      varchar(30) NOT NULL DEFAULT 'pending',
    signature_file_id           bigint,
    certificate_subject         varchar(2000),
    signed_at                   timestamptz,
    annulled_at                 timestamptz,
    annulled_by_user_id         bigint,

    created_at                  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT uq_complaint_signatures_document_role
        UNIQUE (test_complaint_documents_id, signer_role),
    CONSTRAINT uq_complaint_signatures_document_order
        UNIQUE (test_complaint_documents_id, sign_order),
    CONSTRAINT chk_complaint_signatures_role
        CHECK (signer_role IN ('head', 'reviewer', 'coordinator', 'approver')),
    CONSTRAINT chk_complaint_signatures_status
        CHECK (status IN ('pending', 'signed', 'annulled')),
    CONSTRAINT chk_complaint_signatures_pending
        CHECK (status <> 'pending' OR signed_at IS NULL),
    CONSTRAINT chk_complaint_signatures_signed
        CHECK (status <> 'signed'
            OR (signed_at IS NOT NULL AND signature_file_id IS NOT NULL)),
    CONSTRAINT chk_complaint_signatures_annulled
        CHECK (status <> 'annulled' OR annulled_at IS NOT NULL)
);

COMMENT ON TABLE test_complaint_signatures IS
    'Жалобы: ЭЦП версии документа и маршрут подписания';

CREATE INDEX ix_complaint_signatures_signer_pending
    ON test_complaint_signatures (signer_user_id)
    WHERE status = 'pending';


CREATE TABLE test_complaint_attachments (
    id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_app_complaint_id     bigint REFERENCES test_app_complaint (id),
    test_complaint_answers_id bigint REFERENCES test_complaint_answers (id),
    file_id                   bigint      NOT NULL,
    uploaded_by_user_id       bigint      NOT NULL,
    created_at                timestamptz NOT NULL DEFAULT now(),
    deleted_at                timestamptz,

    CONSTRAINT chk_complaint_attachments_owner
        CHECK (num_nonnulls(test_app_complaint_id, test_complaint_answers_id) = 1)
);

COMMENT ON TABLE test_complaint_attachments IS
    'Жалобы: файлы, приложенные к жалобе или к ответу';

CREATE INDEX ix_complaint_attachments_app_complaint
    ON test_complaint_attachments (test_app_complaint_id)
    WHERE test_app_complaint_id IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX ix_complaint_attachments_answer
    ON test_complaint_attachments (test_complaint_answers_id)
    WHERE test_complaint_answers_id IS NOT NULL AND deleted_at IS NULL;


CREATE TABLE test_complaint_status_history (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type   varchar(30) NOT NULL,
    entity_id     bigint      NOT NULL,
    from_status   varchar(30),
    to_status     varchar(30) NOT NULL,
    actor_user_id bigint,                                 -- NULL — система
    comment       varchar(2000),
    created_at    timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT chk_complaint_status_history_entity_type
        CHECK (entity_type IN ('app_complaint', 'buy_complaint', 'buy_complaint_lot'))
);

COMMENT ON TABLE test_complaint_status_history IS
    'Жалобы: журнал переходов статусов жалоб, решений и лотов решений';

CREATE INDEX ix_complaint_status_history_entity
    ON test_complaint_status_history (entity_type, entity_id, created_at);
