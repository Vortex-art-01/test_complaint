-- =====================================================================
-- Модуль «Жалобы». Миграция 003: жалоба поставщика на уровне заявки.
--
--   test_app_complaint       жалоба поставщика (аналог test_app)
--   test_app_complaint_lots  лот жалобы (аналог test_app_lots)
--
-- Выполняется вместе с 002 и 004 в одной транзакции.
--
-- Правило «жалобу подаёт только участник и только по лотам своей заявки»
-- обеспечивается составными внешними ключами:
--   жалоба     (test_app_id, buy_id)                       -> test_app (id, buy_id)
--   лот жалобы (test_app_lots_id, test_app_id, test_buy_lots_id)
--                                                          -> test_app_lots (id, test_app_id, test_buy_lots_id)
--   лот жалобы (test_app_complaint_id, test_app_id)        -> test_app_complaint (id, test_app_id)
-- Лот чужой заявки, лот, на который заявка не подавалась, заявка на другую
-- закупку — отклоняются СУБД.
--
-- Не обеспечивается СУБД, проверяет PHP:
--   - статус заявки и лота заявки, дающий право на жалобу;
--   - соответствие supplier_org_id поставщику заявки;
--   - лот рассмотрения принадлежит тому же решению, что и жалоба;
--   - не больше одной неудалённой жалобы на лот заявки за срок обжалования.
-- =====================================================================

CREATE SEQUENCE test_app_complaint_number_seq;   -- Ж-000001

CREATE TABLE test_app_complaint (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number                varchar(20) NOT NULL
        DEFAULT ('Ж-' || lpad(nextval('test_app_complaint_number_seq')::text, 6, '0')),

    buy_id                bigint      NOT NULL,
    test_app_id           bigint      NOT NULL,
    test_buy_complaint_id bigint,                         -- заполняет система при сборе

    supplier_org_id       bigint      NOT NULL,
    author_user_id        bigint      NOT NULL,
    head_user_id          bigint      NOT NULL,

    contact_phone         varchar(200),                   -- обязательны вне draft
    description           varchar(2000),                  -- лимит 500 проверяет PHP
    requisites_snapshot   jsonb,                          -- реквизиты на момент формирования PDF

    protocol_published_at timestamptz NOT NULL,
    appeal_starts_at      timestamptz NOT NULL,
    appeal_ends_at        timestamptz NOT NULL,

    status                varchar(30) NOT NULL DEFAULT 'draft',
    submitted_at          timestamptz,
    withdrawn_at          timestamptz,

    created_at            timestamptz NOT NULL DEFAULT now(),
    updated_at            timestamptz NOT NULL DEFAULT now(),
    deleted_at            timestamptz,

    -- Заявка принадлежит этой закупке.
    CONSTRAINT fk_app_complaint_app_buy
        FOREIGN KEY (test_app_id, buy_id) REFERENCES test_app (id, buy_id),
    -- Решение относится к этой же закупке.
    CONSTRAINT fk_app_complaint_buy_complaint
        FOREIGN KEY (test_buy_complaint_id, buy_id) REFERENCES test_buy_complaint (id, buy_id),

    CONSTRAINT uq_app_complaint_id_app
        UNIQUE (id, test_app_id),
    CONSTRAINT uq_app_complaint_number
        UNIQUE (number),
    CONSTRAINT chk_app_complaint_status
        CHECK (status IN ('draft', 'awaiting_signature', 'signed',
                          'submitted', 'withdrawn', 'in_review', 'reviewed')),
    CONSTRAINT chk_app_complaint_appeal_period
        CHECK (appeal_starts_at < appeal_ends_at),
    CONSTRAINT chk_app_complaint_filled
        CHECK (status = 'draft'
            OR (contact_phone IS NOT NULL AND description IS NOT NULL)),
    CONSTRAINT chk_app_complaint_submitted
        CHECK (status NOT IN ('submitted', 'in_review', 'reviewed')
            OR submitted_at IS NOT NULL),
    CONSTRAINT chk_app_complaint_in_review
        CHECK (status NOT IN ('in_review', 'reviewed') OR test_buy_complaint_id IS NOT NULL),
    CONSTRAINT chk_app_complaint_delete_only_before_submission
        CHECK (deleted_at IS NULL
            OR status IN ('draft', 'awaiting_signature', 'signed'))
);

ALTER SEQUENCE test_app_complaint_number_seq OWNED BY test_app_complaint.number;

COMMENT ON TABLE test_app_complaint IS
    'Жалобы: жалоба поставщика по своей заявке';

CREATE INDEX ix_app_complaint_supplier_created
    ON test_app_complaint (supplier_org_id, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX ix_app_complaint_head_awaiting_signature
    ON test_app_complaint (head_user_id)
    WHERE status = 'awaiting_signature' AND deleted_at IS NULL;

CREATE INDEX ix_app_complaint_submitted_appeal_end
    ON test_app_complaint (appeal_ends_at, buy_id)
    WHERE status = 'submitted';

CREATE INDEX ix_app_complaint_app
    ON test_app_complaint (test_app_id);

CREATE INDEX ix_app_complaint_buy_complaint
    ON test_app_complaint (test_buy_complaint_id)
    WHERE test_buy_complaint_id IS NOT NULL;


-- Вердикт и ответ — на уровне лота жалобы.
CREATE TABLE test_app_complaint_lots (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_app_complaint_id      bigint      NOT NULL,
    test_app_id                bigint      NOT NULL,
    test_app_lots_id           bigint      NOT NULL,
    test_buy_lots_id           bigint      NOT NULL,

    test_buy_complaint_lots_id bigint,                    -- заполняет система при сборе
    verdict                    varchar(30),
    test_complaint_answers_id  bigint,
    reviewed_at                timestamptz,

    created_at                 timestamptz NOT NULL DEFAULT now(),
    updated_at                 timestamptz NOT NULL DEFAULT now(),
    deleted_at                 timestamptz,

    -- Лот жалобы принадлежит жалобе по той же заявке.
    CONSTRAINT fk_app_complaint_lots_complaint_app
        FOREIGN KEY (test_app_complaint_id, test_app_id)
        REFERENCES test_app_complaint (id, test_app_id),
    -- Лот заявки принадлежит этой заявке и этому лоту закупки.
    CONSTRAINT fk_app_complaint_lots_app_lot
        FOREIGN KEY (test_app_lots_id, test_app_id, test_buy_lots_id)
        REFERENCES test_app_lots (id, test_app_id, test_buy_lots_id),
    -- Лот решения — тот же лот закупки.
    CONSTRAINT fk_app_complaint_lots_buy_complaint_lot
        FOREIGN KEY (test_buy_complaint_lots_id, test_buy_lots_id)
        REFERENCES test_buy_complaint_lots (id, test_buy_lots_id),
    -- Ответ дан по тому же лоту решения.
    CONSTRAINT fk_app_complaint_lots_answer
        FOREIGN KEY (test_complaint_answers_id, test_buy_complaint_lots_id)
        REFERENCES test_complaint_answers (id, test_buy_complaint_lots_id),

    CONSTRAINT chk_app_complaint_lots_verdict
        CHECK (verdict IN ('satisfied', 'rejected')),
    CONSTRAINT chk_app_complaint_lots_review_needs_buy_complaint_lot
        CHECK (test_buy_complaint_lots_id IS NOT NULL
            OR (verdict IS NULL AND test_complaint_answers_id IS NULL AND reviewed_at IS NULL)),
    CONSTRAINT chk_app_complaint_lots_reviewed
        CHECK (reviewed_at IS NULL
            OR (verdict IS NOT NULL AND test_complaint_answers_id IS NOT NULL)),
    CONSTRAINT chk_app_complaint_lots_not_deleted_in_review
        CHECK (deleted_at IS NULL OR test_buy_complaint_lots_id IS NULL)
);

COMMENT ON TABLE test_app_complaint_lots IS
    'Жалобы: лот жалобы — лот заявки, вердикт, ссылка на ответ';

CREATE UNIQUE INDEX uq_app_complaint_lots_complaint_buy_lot
    ON test_app_complaint_lots (test_app_complaint_id, test_buy_lots_id)
    WHERE deleted_at IS NULL;

-- Жалоба подаётся строго на один лот.
CREATE UNIQUE INDEX uq_app_complaint_lots_single
    ON test_app_complaint_lots (test_app_complaint_id)
    WHERE deleted_at IS NULL;

CREATE INDEX ix_app_complaint_lots_app_lot
    ON test_app_complaint_lots (test_app_lots_id);

CREATE INDEX ix_app_complaint_lots_buy_lot
    ON test_app_complaint_lots (test_buy_lots_id)
    WHERE deleted_at IS NULL;

CREATE INDEX ix_app_complaint_lots_buy_complaint_lot
    ON test_app_complaint_lots (test_buy_complaint_lots_id)
    WHERE test_buy_complaint_lots_id IS NOT NULL;

CREATE INDEX ix_app_complaint_lots_answer
    ON test_app_complaint_lots (test_complaint_answers_id)
    WHERE test_complaint_answers_id IS NOT NULL;
